#!/usr/bin/env python
"""merge_link_audit_fulltext.py — fold the one-pair link audit (link_audit_fulltext.py) into the paper-link inputs (R2026.39).

Reads OUT/pairs_*.parquet and the earlier link-audit tables (stage11_merged, then stage13_merged, stage14_merged — the order
prepare_catalog_inputs.py merges them in) and writes, under <cache>/large_update/stage17_deep_pass/:
  link_audit.parquet        study_accession, relation, paper_id, n — ALL audit rows of every project this audit touched
                            (prepare_catalog_inputs replaces a project's rows wholesale): the earlier rows, with a pair's
                            verdict replaced when the new audit decided it (generated / reused / unrelated)
  paper_candidates.parquet  paper metadata of the pairs (same columns as find_papers.py)
  link_evidence.parquet     study_accession, paper_id, evidence_quote, evidence_source, link_basis, link_audit for the
                            pairs committed as generated by this audit
  links_not_committed_part.csv  pairs both readings called generated that were NOT committed because the scope check found the
                            paper accounts for only a part of the project (umbrella / resource accession, combined deposit,
                            cohort accession shared by sibling papers) — the list for a later per-sample assignment
A link is committed when two readings call the paper the generator AND the scope check says it accounts for the project as a
whole. Checked by Opus 5 readers on 75 committed pairs before the scope check existed: 69 right; of the 6 that were not, the
scope check keeps 5 out, and it keeps out 7 of the 69 right ones.

usage: python scripts/merge_link_audit_fulltext.py --audit-out ~/catalog/cache/deep_pass/a3/audit_out [--cache ~/catalog/cache]
"""
import argparse, glob, json, os, sys
import pandas as pd


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--audit-out", required=True); ap.add_argument("--cache", default=os.path.expanduser("~/catalog/cache"))
    ap.add_argument("--pairs", default=None, help="the pair list given to the audit (paper metadata)")
    a = ap.parse_args(argv)
    L = os.path.join(a.cache, "large_update"); out = os.path.join(L, "stage17_deep_pass"); os.makedirs(out, exist_ok=True)
    new = pd.concat([pd.read_parquet(f) for f in sorted(glob.glob(os.path.join(a.audit_out, "pairs_*.parquet")))], ignore_index=True)
    new["paper_id"] = new.paper_id.astype(str)
    la = pd.read_parquet(os.path.join(L, "stage11_merged", "link_audit.parquet"))
    for d in ("stage13_merged", "stage14_merged"):
        p = os.path.join(L, d, "link_audit.parquet")
        if os.path.exists(p):
            d2 = pd.read_parquet(p)
            la = pd.concat([la[~la.study_accession.isin(set(d2.study_accession))], d2], ignore_index=True)
    la["paper_id"] = la.paper_id.astype(str)
    la["key"] = la.paper_id.str.replace("MED:", "", regex=False)
    new["key"] = new.paper_id.str.replace("MED:", "", regex=False)
    # scope check (link_audit_fulltext.py --scope-check): a link is committed only when the paper accounts for the project as a
    # whole. `part` (umbrella or resource accession, combined deposit, shared cohort accession) and `none` are kept out and listed.
    sc_files = sorted(glob.glob(os.path.join(a.audit_out, "scope", "scope_*.parquet")))
    if not sc_files:
        sys.exit("no scope-check output: run link_audit_fulltext.py --scope-check before merging")
    sc = pd.concat([pd.read_parquet(f) for f in sc_files], ignore_index=True).astype({"paper_id": str}).drop_duplicates(["study_accession", "paper_id"])
    new = new.drop_duplicates(["study_accession", "paper_id"]).merge(sc[["study_accession", "paper_id", "link_scope", "scope_reason", "scope_status"]],
                                                                   on=["study_accession", "paper_id"], how="left")
    gen = new.relation.eq("generated")
    new.loc[gen & new.link_scope.eq("part"), "relation"] = "generated_part_not_committed"
    new.loc[gen & ~new.link_scope.isin(["whole", "part"]), "relation"] = "unclear"          # none / cannot_tell / check refused or not run
    second = new[new.relation.eq("generated_part_not_committed")]
    second[["study_accession", "paper_id", "title", "year", "basis", "text_mode", "link_scope", "scope_reason"]].to_csv(
        os.path.join(out, "links_not_committed_part.csv"), index=False)
    decided = new[new.relation.isin(["generated", "reused", "unrelated"])]
    old = la[la.study_accession.isin(set(new.study_accession))].copy()
    old_id = old.drop_duplicates(["study_accession", "key"]).set_index(["study_accession", "key"]).paper_id.to_dict()
    decided = decided.assign(paper_id=[old_id.get((s, k), k) for s, k in zip(decided.study_accession, decided.key)])
    dk = set(zip(decided.study_accession, decided.key))
    old = old[[(s, k) not in dk for s, k in zip(old.study_accession, old.key)]]
    other = new[~new.relation.isin(["generated", "reused", "unrelated"])]
    ok_ = set(zip(old.study_accession, old.key))
    other = other[[(s, k) not in ok_ for s, k in zip(other.study_accession, other.key)]]      # an undecided pair keeps its earlier row if it has one
    other = other.assign(paper_id=other.key, relation=other.relation.where(other.relation.isin(["unclear", "generated_part_not_committed"]), "unclear"))
    rows = pd.concat([old[["study_accession", "relation", "paper_id"]], decided[["study_accession", "relation", "paper_id"]],
                      other[["study_accession", "relation", "paper_id"]]], ignore_index=True).drop_duplicates(["study_accession", "paper_id"], keep="last")
    rows["n"] = rows.groupby("study_accession").paper_id.transform("size")
    rows.to_parquet(os.path.join(out, "link_audit.parquet"), index=False)
    pc_cols = ["study_accession", "paper_id", "pmid", "pmcid", "doi", "title", "journal", "year", "methods"]
    pc = pd.concat([decided, other], ignore_index=True).reindex(columns=pc_cols)
    for c in ("pmid", "pmcid", "doi", "title", "journal", "year", "methods"):
        pc[c] = pc[c].map(lambda v: None if v is None or str(v) in ("nan", "None", "") else str(v))
    pc.to_parquet(os.path.join(out, "paper_candidates.parquet"), index=False)
    ev = decided[decided.relation.eq("generated")]
    ev = pd.DataFrame({"study_accession": ev.study_accession, "paper_id": ev.paper_id, "evidence_quote": ev.quote, "evidence_source": ev.quote_source,
                       "link_basis": ev.basis, "link_audit": "pair audit with full-text context, Opus 5 check and scope check (R2026.39)"})
    ev.to_parquet(os.path.join(out, "link_evidence.parquet"), index=False)
    had_gen = set(la[la.relation.eq("generated")].study_accession)
    summ = {"pairs_audited": int(len(new)), "projects_audited": int(new.study_accession.nunique()),
            "relation": new.relation.value_counts().to_dict(), "text_mode": new.text_mode.value_counts().to_dict(),
            "status_first": new.status.value_counts(dropna=False).to_dict(),
            "projects_with_new_generating_paper": int(ev.study_accession.nunique()),
            "of_which_had_none_before": int(len(set(ev.study_accession) - had_gen)),
            "generated_pairs_committed": int(len(ev)), "generated_part_not_committed": int(len(second)),
            "scope": new.loc[new.link_scope.notna(), "link_scope"].value_counts().to_dict(),
            "generated_by_basis": ev.link_basis.value_counts().to_dict()}
    json.dump(summ, open(os.path.join(out, "summary.json"), "w"), indent=1, default=str)
    print(json.dumps(summ, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(main())
